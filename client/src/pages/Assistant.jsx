import { useRef, useState } from 'react';
import { api } from '../api.js';
import { ProGate } from './Plan.jsx';

const EXAMPLES = ['Which hackathons near me fit my resume?', 'Online AI competitions with big prizes closing this month', 'What should I add to my skills to qualify for more events?'];

function Chat() {
  const [msgs, setMsgs] = useState([]);
  const [q, setQ] = useState('');
  const [busy, setBusy] = useState(false);
  const end = useRef(null);

  async function send(text) {
    const question = text.trim();
    if (question.length < 3 || busy) return;
    setQ(''); setBusy(true);
    const history = msgs.map((m) => ({ role: m.role, text: m.text }));
    setMsgs((m) => [...m, { role: 'user', text: question }]);
    try {
      const r = await api.chat(question, history);
      setMsgs((m) => [...m, { role: 'assistant', text: r.answer, citations: r.citations, mode: r.mode, usedResume: r.usedResume }]);
    } catch (e) { setMsgs((m) => [...m, { role: 'assistant', text: e.message, error: true }]); }
    finally { setBusy(false); setTimeout(() => end.current?.scrollIntoView({ behavior: 'smooth' }), 50); }
  }
  return (
    <>
      <h1>Assistant</h1>
      <p className="muted">Answers are grounded in live listings plus your resume and location, with sources you can open.</p>
      <div className="chat" aria-live="polite">
        {!msgs.length && <div className="chips">{EXAMPLES.map((x) => <button key={x} className="chip" onClick={() => send(x)}>{x}</button>)}</div>}
        {msgs.map((m, i) => (
          <div key={i} className={`bubble ${m.role} ${m.error ? 'error' : ''}`}>
            <p>{m.text}</p>
            {m.citations?.length > 0 && (
              <ol className="cites">{m.citations.map((c) => <li key={c.id}><a href={c.url} target="_blank" rel="noreferrer">{c.title}</a> <span className="muted small">{c.score}% match</span></li>)}</ol>
            )}
            {m.mode && <p className="small muted">{m.mode === 'gemini' ? 'Generated by Gemini from retrieved listings' : 'Built from your top retrieved matches'}{m.usedResume ? ' · used your resume' : ''}</p>}
          </div>
        ))}
        {busy && <div className="bubble assistant"><p className="muted">Searching listings…</p></div>}
        <div ref={end} />
      </div>
      <form className="ask" onSubmit={(e) => { e.preventDefault(); send(q); }}>
        <input value={q} onChange={(e) => setQ(e.target.value)} maxLength={500} placeholder="Ask about events, deadlines, fit…" aria-label="Your question" />
        <button className="btn primary" disabled={busy}>Send</button>
      </form>
    </>
  );
}

export default function Assistant() { return <ProGate what="The assistant"><Chat /></ProGate>; }
